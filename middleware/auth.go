func validUserInfo(username string, role int) bool {
	// check username is empty
	if strings.TrimSpace(username) == "" {
		return false
	}
	if !common.IsValidateRole(role) {
		return false
	}
	return true
}

// authenticateUser performs session/access-token authentication, threshold
// check, and context setup (c.Set). It does NOT call c.Next() and does NOT
// start admin audit — callers are responsible for invoking c.Next() and the
// audit lifecycle.
//
// On authentication/authorization failure it writes an error response and
// calls c.Abort(), so callers MUST check c.IsAborted() before proceeding.
//
// Split from authHelper so that DistributorAuth can perform its precise-match
// check (role == RoleDistributorUser) BEFORE c.Next() runs the downstream
// handler. Without this split, authHelper's c.Next() would execute the handler
// before DistributorAuth's 403 could be written — a Rule 1 bug surfaced by the
// 02-04 DistributorAuth test suite (admin/root returned 200 instead of 403).
func authenticateUser(c *gin.Context, minRole int) {
	session := sessions.Default(c)
	username := session.Get("username")
	role := session.Get("role")
	id := session.Get("id")
	status := session.Get("status")
	useAccessToken := false
	if username == nil {
		// Check access token
		accessToken := c.Request.Header.Get("Authorization")
		if accessToken == "" {
			c.JSON(http.StatusUnauthorized, gin.H{
				"success": false,
				"message": common.TranslateMessage(c, i18n.MsgAuthNotLoggedIn),
			})
			c.Abort()
			return
		}
		user, authErr := model.ValidateAccessToken(accessToken)
		if authErr != nil {
			if errors.Is(authErr, model.ErrDatabase) {
				common.SysLog("ValidateAccessToken database error: " + authErr.Error())
				c.JSON(http.StatusInternalServerError, gin.H{
					"success": false,
					"message": common.TranslateMessage(c, i18n.MsgDatabaseError),
				})
			} else {
				c.JSON(http.StatusOK, gin.H{
					"success": false,
					"message": common.TranslateMessage(c, i18n.MsgAuthAccessTokenInvalid),
				})
			}
			c.Abort()
			return
		}
		if user != nil && user.Username != "" {
			if !validUserInfo(user.Username, user.Role) {
				c.JSON(http.StatusOK, gin.H{
					"success": false,
					"message": common.TranslateMessage(c, i18n.MsgAuthUserInfoInvalid),
				})
				c.Abort()
				return
			}
			// Token is valid
			username = user.Username
			role = user.Role
			id = user.Id
			status = user.Status
			useAccessToken = true
		} else {
			c.JSON(http.StatusOK, gin.H{
				"success": false,
				"message": common.TranslateMessage(c, i18n.MsgAuthAccessTokenInvalid),
			})
			c.Abort()
			return
		}
	}
	// Session lifetime check: only applies to cookie sessions (reaching this point with
	// useAccessToken == false means username is necessarily non-nil); the Authorization
	// access-token path neither reads nor writes timestamps and is not checked here.
	if !useAccessToken {
		now := time.Now().Unix()
		if reason, expired := sessionLifetimeExpired(session, now); expired {
			common.SysLog(fmt.Sprintf("session expired (reason=%s, user_id=%v)", reason, id))
			if err := clearSessionCookie(session); err != nil {
				common.SysLog("failed to clear expired session cookie: " + err.Error())
			}
			c.JSON(http.StatusUnauthorized, gin.H{
				"success": false,
				"message": common.TranslateMessage(c, i18n.MsgAuthNotLoggedIn),
			})
			c.Abort()
			return
		}
		// Sliding renewal throttle: write last_active back only once 60 seconds have passed,
		// avoiding a cookie rewrite on every request.
		if now-sessionValueInt64(session.Get(common.SessionKeyLastActive)) >= common.SessionTouchIntervalSeconds {
			session.Set(common.SessionKeyLastActive, now)
			if err := session.Save(); err != nil {
				common.SysLog("failed to touch session last_active: " + err.Error())
			}
		}
	}
	// get header New-Api-User
	apiUserIdStr := c.Request.Header.Get("New-Api-User")
	if apiUserIdStr == "" {
		c.JSON(http.StatusUnauthorized, gin.H{
			"success": false,
			"message": common.TranslateMessage(c, i18n.MsgAuthUserIdNotProvided),
		})
		c.Abort()
		return
	}
	apiUserId, err := strconv.Atoi(apiUserIdStr)
	if err != nil {
		c.JSON(http.StatusUnauthorized, gin.H{
			"success": false,
			"message": common.TranslateMessage(c, i18n.MsgAuthUserIdFormatError),
		})
		c.Abort()
		return

	}
	if id != apiUserId {
		c.JSON(http.StatusUnauthorized, gin.H{
			"success": false,
			"message": common.TranslateMessage(c, i18n.MsgAuthUserIdMismatch),
		})
		c.Abort()
		return
	}
	if status.(int) == common.UserStatusDisabled {
		c.JSON(http.StatusOK, gin.H{
			"success": false,
			"message": common.TranslateMessage(c, i18n.MsgAuthUserBanned),
		})
		c.Abort()
		return
	}
	if role.(int) < minRole {
		c.JSON(http.StatusOK, gin.H{
			"success": false,
			"message": common.TranslateMessage(c, i18n.MsgAuthInsufficientPrivilege),
		})
		c.Abort()
		return
	}
	if !validUserInfo(username.(string), role.(int)) {
		c.JSON(http.StatusOK, gin.H{
			"success": false,
			"message": common.TranslateMessage(c, i18n.MsgAuthUserInfoInvalid),
		})
		c.Abort()
		return
	}
	// Prevent conflicts between different newapi versions that would make data incompatible.
	c.Header("Auth-Version", "864b7076dbcd0a3c01b5520316720ebf")
	c.Set("username", username)
	c.Set("role", role)
	c.Set("id", id)
	c.Set("group", session.Get("group"))
	c.Set("user_group", session.Get("group"))
	c.Set("use_access_token", useAccessToken)
	// Distributor flag: injected after authHelper passes the threshold, so downstream
	// handlers/middleware can make precise decisions on demand.
	// Note: is_distributor only indicates that role == RoleDistributorUser; it does not
	// replace the precise gating of DistributorAuth. Although admin/root also pass
	// authHelper(c, RoleDistributorUser)'s threshold (5>=1), is_distributor is false for
	// them; entering the distributor view requires the second precise check in DistributorAuth.
	c.Set("is_distributor", role.(int) == common.RoleDistributorUser)
}

// sessionValueInt64 normalizes session value types: the cookie store always round-trips
// through gob as int64, while the remaining branches guard against legacy int values and
// future store changes (e.g. JSON serialization producing float64).
func sessionValueInt64(value interface{}) int64 {
	switch v := value.(type) {
	case int64:
		return v
	case int:
		return int64(v)
	case int32:
		return int64(v)
	case float64:
		return int64(v)
	default:
		return 0
	}
}

// sessionLifetimeExpired determines whether the session has timed out. Four cases are
// treated as expired: a missing timestamp (sessions issued before deployment), 30 minutes
// idle, 12 hours since login, or last_active later than the current time (clock rollback or
// tampering). The reason is returned to make log attribution easier.
func sessionLifetimeExpired(session sessions.Session, now int64) (string, bool) {
	loginAt := sessionValueInt64(session.Get(common.SessionKeyLoginAt))
	lastActive := sessionValueInt64(session.Get(common.SessionKeyLastActive))
	if loginAt == 0 || lastActive == 0 {
		return "missing_timestamp", true
	}
	if lastActive > now {
		return "future_last_active", true
	}
	if now-lastActive >= common.SessionIdleTimeoutSeconds {
		return "idle_timeout", true
	}
	if now-loginAt >= common.SessionAbsoluteTimeoutSeconds {
		return "absolute_timeout", true
	}
	return "", false
}

// clearSessionCookie clears the session values and makes the browser delete the session
// cookie immediately (MaxAge: -1).
func clearSessionCookie(session sessions.Session) error {
	session.Clear()
	session.Options(sessions.Options{
		Path:     "/",
		MaxAge:   -1,
		HttpOnly: true,
		Secure:   false,
		SameSite: http.SameSiteStrictMode,
	})
	return session.Save()
}

// authHelper authenticates the user (via authenticateUser) and, on success,
// runs the downstream handler chain with admin-audit lifecycle when minRole
// indicates an admin/root endpoint. UserAuth/AdminAuth/RootAuth use this
// wrapper unchanged; DistributorAuth calls authenticateUser directly so it can
// insert its precise-match check before c.Next() (see DistributorAuth comment).
func authHelper(c *gin.Context, minRole int) {
	authenticateUser(c, minRole)
	if c.IsAborted() {
		return
	}
	// Fallback audit for admin/root write operations: folded into the auth chain so that every
	// write endpoint passing through AdminAuth/RootAuth is audited automatically (no separate
	// audit middleware on each route, which could be forgotten).
	// Handlers that instrument the audit manually set ContextKeyAuditLogged, and
	// finishAdminAudit skips those accordingly.
	var auditWriter *auditResponseWriter
	if minRole >= common.RoleAdminUser {
		auditWriter = beginAdminAudit(c)
	}

	c.Next()

	finishAdminAudit(c, auditWriter)
}

func TryUserAuth() func(c *gin.Context) {
	return func(c *gin.Context) {
		session := sessions.Default(c)
		id := session.Get("id")
		if id != nil {
			c.Set("id", id)
		}
		c.Next()
	}
}

func UserAuth() func(c *gin.Context) {
	return func(c *gin.Context) {
		authHelper(c, common.RoleCommonUser)
	}
}

