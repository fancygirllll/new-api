package model

// CommissionFlow is the commission flow table (contract 01-CONTRACT.md §3.1 frozen).
// All amounts are int64 cents; rates are int basis points (x10000) (§3.0 precision decision).
type CommissionFlow struct {
	Id              int64  `json:"id" gorm:"primaryKey"`
	BillingNo       string `json:"billing_no" gorm:"type:varchar(64);uniqueIndex:uk_flow_billing,unique"` // Idempotency key; see contract §3.1.1
	FlowType        string `json:"flow_type" gorm:"type:varchar(20);uniqueIndex:uk_flow_billing,unique"`  // commission | reversal | manual_credit | manual_debit
	TradeNo         string `json:"trade_no" gorm:"type:varchar(255);index:idx_flow_trade"`                // Related top-up order number; empty for manual entries
	CustomerId      int    `json:"customer_id" gorm:"type:int;index:idx_flow_customer"`
	DistributorId   int    `json:"distributor_id" gorm:"type:int;index:idx_flow_distributor"`
	TopupMoneyCents int64  `json:"topup_money_cents" gorm:"type:bigint"`                               // Top-up amount snapshot (cents)
	RateBp          int    `json:"rate_bp" gorm:"type:int"`                                            // Rate snapshot (basis points, RATE-02)
	AmountCents     int64  `json:"amount_cents" gorm:"type:bigint"`                                    // Commission amount of this flow (cents); negative for reversals
	Status          string `json:"status" gorm:"type:varchar(20);index:idx_flow_status"`               // pending | available
	Period          string `json:"period" gorm:"type:varchar(7);index:idx_flow_period"`                // Period "2026-08" (calendar month of the credit time)
	StatementId     int64  `json:"statement_id" gorm:"type:bigint;default:0;index:idx_flow_statement"` // Backfilled at statement generation
	RelatedFlowId   int64  `json:"related_flow_id" gorm:"type:bigint;default:0"`                       // Original flow ID that a reversal points to
	Reason          string `json:"reason" gorm:"type:varchar(255)"`                                    // Reversal/manual entry reason (required in some cases)
	OperatorId      int    `json:"operator_id" gorm:"type:int;default:0"`                              // Human operator; 0 for system flows
	CreatedAt       int64  `json:"created_at" gorm:"autoCreateTime;column:created_at"`
}

// FlowType enum (contract §3.1 frozen).
const (
	CommissionFlowCommission   = "commission"    // Positive commission (generated when a top-up is credited)
	CommissionFlowReversal     = "reversal"      // Negative reversal (generated by refunds/voids)
	CommissionFlowManualCredit = "manual_credit" // Super-admin manual credit (COMM-05)
	CommissionFlowManualDebit  = "manual_debit"  // Super-admin manual debit (COMM-05)

	CommissionFlowPending   = "pending"   // Not yet statemented
	CommissionFlowAvailable = "available" // Included in a statement
)

// TableName explicitly specifies the table name (contract §3.1 frozen).
func (CommissionFlow) TableName() string { return "commission_flows" }
